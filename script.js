// ==========================================
// ЗАДАЧА 3: Перекрашивание всех карточек
// ==========================================
// Находим абсолютно все карточки на странице
const allCards = document.querySelectorAll('.product-card');

// Запускаем цикл, который пройдётся по каждой карточке
allCards.forEach(function(card) {
  // Меняем цвет фона каждой карточки на светло-голубой (или любой другой)
  card.style.backgroundColor = '#e1f5fe';
});


// ==========================================
// ЗАДАЧА 5: Консоль лог и alert
// ==========================================
console.log('Скрипт успешно запущен, карточки перекрашены!');
alert('JavaScript работает! Нажмите ОК, чтобы увидеть карточки.');


// ==========================================
// ЗАДАЧА 6: Слушатель наведения на заголовок h1
// ==========================================
// Находим заголовок по тегу
const mainTitle = document.querySelector('h1');

// Добавляем слушатель события "mouseenter" (наведение курсора мыши)
mainTitle.addEventListener('mouseenter', function() {
  // Выводим в консоль именно контент элемента, а не текст от руки
  console.log(mainTitle.textContent);
});
// Находим нашу добавленную кнопку
const myButton = document.querySelector('.toggle-btn');

// Слушаем клик по ней
myButton.addEventListener('click', function() {
  // Метод toggle сам добавит класс, если его нет, и уберёт, если он есть
  myButton.classList.toggle('toggle-btn--active');
});
